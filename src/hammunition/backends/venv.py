def write_requirements(path: Path, lines: list[str]) -> str:
    """Stage the manifest's pinned requirements as a file pip can read."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return f"wrote {len(lines)} pinned requirement line(s) to {path}"


#: The second line of every wrapper this backend writes. It is the proof of
#: ownership (#288): an entry in the operator's ``bin`` directory is replaced
#: only when it is exactly the file this backend would have written. The unit
#: name is part of it, so one unit never replaces another unit's wrapper
#: unseen. The same text is what ``uninstall`` reads back
#: (``execute.OURS_MARKERS``, ``uninstall._launcher_owner``).
WRAPPER_MARKER = "# generated by hammunition for "

#: A wrapper is two lines and a header; anything larger is not one, and is
#: refused unread rather than slurped (a FIFO or a multi-gigabyte file in the
#: operator's PATH is somebody's, and reading it is not our business).
MAX_WRAPPER_BYTES = 4096

_TEXT_ENCODING = "utf-8"


class WrapperRefused(BackendError):
    """An entry in the operator's bin directory the engine will not touch.

    Raised at write time; the same finding at plan time is a
    :class:`~hammunition.plan.Blocker` (:func:`~hammunition.plan.venv_wrapper_blockers`).
    """


def wrapper_text(unit: str, target: Path) -> str:
    """The exact bytes of a wrapper: shebang, ownership header, exec.

    Generated rather than symlinked: a symlink into a venv makes some
    entry-point loaders resolve ``sys.prefix`` to the link's home and miss the
    venv's packages; ``exec`` of the venv's own script never does.
    """
    return f'#!/bin/sh\n{WRAPPER_MARKER}{unit}\nexec "{target}" "$@"\n'


def _header_pattern() -> re.Pattern[str]:
    return re.compile(
        r"#!/bin/sh\n" + re.escape(WRAPPER_MARKER) + r'(?P<unit>[^\n]+)\nexec "[^"\n]+" "\$@"\n'
    )


def _legacy_pattern(unit: str, script: str) -> re.Pattern[str]:
    # Every wrapper written before #288: two lines, no header, exec'ing into
    # this unit's own script in the engine's venv tree. Recognised so that a
    # re-install over one keeps working; the exact shape and the unit-named
    # venv path are what make it ours and not a pip script.
    return re.compile(
        r'#!/bin/sh\nexec "[^"\n]*/venvs/'
        + re.escape(unit)
        + "/bin/"
        + re.escape(script)
        + r'" "\$@"\n'
    )


#: The ownership rule of one kind of wrapper: given the text found at *name* and
#: the unit installing, ``("ours", "")`` or ``("foreign", why)``. The venv rule is
#: :func:`venv_ownership`; the node backend supplies its own (#406). Everything
#: else about reaching and replacing the entry is shared.
Ownership = Callable[[str, str, str], tuple[str, str]]


def _classify(
    dir_fd: int, name: str, unit: str, ownership: Ownership | None = None
) -> tuple[str, str]:
    """What is at *name* in the directory *dir_fd*: ``(state, why)``.

    *state* is ``absent``, ``ours`` or ``foreign``; *why* says what made it
    foreign, in words an operator can act on. Nothing here follows a symbolic
    link, blocks on a FIFO or reads more than :data:`MAX_WRAPPER_BYTES`. Whether
    the bytes are ours is *ownership*'s call (the venv rule when None).
    """
    try:
        st = os.stat(name, dir_fd=dir_fd, follow_symlinks=False)
    except FileNotFoundError:
        return "absent", ""
    except OSError as exc:
        return "foreign", f"it cannot be inspected ({exc.strerror or exc})"
    if stat.S_ISLNK(st.st_mode):
        try:
            where = os.readlink(name, dir_fd=dir_fd)
        except OSError:
            where = "an unreadable destination"
        return "foreign", (
            f"it is a symbolic link to {where} (a pipx install leaves these), and a "
            f"wrapper is never written through a link"
        )
    if not stat.S_ISREG(st.st_mode):
        return "foreign", "it is not a regular file (a directory, FIFO or device)"
    if st.st_size > MAX_WRAPPER_BYTES:
        return "foreign", f"it is too large to be a wrapper ({st.st_size} bytes)"
    try:
        # O_NONBLOCK so a FIFO swapped in after the stat cannot hang the open;
        # O_NOFOLLOW so a link swapped in cannot be read through.
        fd = os.open(
            name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=dir_fd
        )
    except OSError as exc:
        return "foreign", f"it cannot be read ({exc.strerror or exc})"
    try:
        opened = os.fstat(fd)
        if not stat.S_ISREG(opened.st_mode):
            return "foreign", "it is not a regular file (a directory, FIFO or device)"
        raw = os.read(fd, MAX_WRAPPER_BYTES + 1)
    except OSError as exc:
        return "foreign", f"it cannot be read ({exc.strerror or exc})"
    finally:
        os.close(fd)
    if len(raw) > MAX_WRAPPER_BYTES:
        return "foreign", "it is too large to be a wrapper"
    try:
        text = raw.decode(_TEXT_ENCODING)
    except UnicodeDecodeError:
        return "foreign", "it is not a text script"
    return (ownership or venv_ownership)(text, unit, name)


def header_ownership(
    text: str, unit: str, header: re.Pattern[str], legacy: re.Pattern[str] | None = None
) -> tuple[str, str]:
    """Judge *text* against a wrapper *header* pattern with a ``unit`` group.

    The exact-shape rule both backends share: the whole text must match, the
    unit in the header must be the installing one, and anything else is
    someone's.
    """
    found = header.fullmatch(text)
    if found is not None:
        owner = found.group("unit")
        if owner == unit:
            return "ours", ""
        return "foreign", (
            f"it is the wrapper Hammunition wrote for the unit {owner}, which has the same "
            f"command name as {unit}"
        )
    if legacy is not None and legacy.fullmatch(text) is not None:
        return "ours", ""
    return "foreign", "it does not carry the header Hammunition's wrappers carry"


def venv_ownership(text: str, unit: str, name: str) -> tuple[str, str]:
    """The venv wrapper's rule: its exact two-line shape, or the pre-#288 one."""
    return header_ownership(text, unit, _header_pattern(), _legacy_pattern(unit, name))


def _refusal(path: Path, unit: str, why: str) -> str:
    return (
        f"{path} already exists and Hammunition did not write it: {why}. "
        f"It is left alone (D-022: coexist, never replace silently) and {unit}'s command "
        f"cannot be put on the PATH under that name until it is gone."
    )


def _open_bin_dir(path: Path, *, create: bool) -> int | None:
    """A descriptor on the operator's ``bin`` directory, or None if absent.

    As the operator, a symlinked directory is followed: ``~/.local/bin`` is the
    operator's own and linking it into a dotfiles tree is their layout, not an
    escape -- nothing crosses a privilege boundary. As root writing on an
    operator's behalf (sudo), every component under their home is walked
    ``O_NOFOLLOW`` and a link is refused by name
    (:func:`hammunition.paths.open_operator_dir`), so a link planted in the
    operator's tree cannot steer a root write. Whatever the case, the entry
    itself is only ever reached through this descriptor, never by path again.
    """
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC
    try:
        if operator_for(path) is not None:
            if create:
                fd = open_operator_dir(path)
                if fd is not None:
                    return fd
            else:
                problem = operator_dir_problem(path)
                if problem is not None:
                    raise WrapperRefused(problem)
            flags |= os.O_NOFOLLOW
        elif create:
            path.mkdir(parents=True, exist_ok=True)
        return os.open(path, flags)
    except OperatorDirError as exc:
        raise WrapperRefused(str(exc)) from exc
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise WrapperRefused(f"{path} cannot be opened: {exc.strerror or exc}") from exc


def wrapper_name_problem(path: Path, bin_dir: Path | None = None) -> str | None:
    """Why *path* is not a wrapper directly inside the operator's ``bin`` directory.

    The schema already refuses an unsafe ``expose`` name; this is the second
    look, on the path itself, for an object built around validation. The name
    must be one safe basename and the path's parent exactly *bin_dir* (lexically:
    no ``..`` component can be hiding in it, and an absolute name that discarded
    *bin_dir* when joined is caught by the parent mismatch). Without *bin_dir*
    a ``..`` component anywhere in the path is refused.
    """
    problem = command_name_problem(path.name)
    if problem is not None:
        return f"the command name {path.name!r} {problem}"
    if ".." in path.parts:
        return f"{path} has a '..' component and could leave the bin directory"
    if bin_dir is not None and path.parent != bin_dir:
        return f"{path} is not directly inside {bin_dir}"
    return None


def wrapper_conflict(
    path: Path, unit: str, bin_dir: Path | None = None, ownership: Ownership | None = None
) -> str | None:
    """Why *path* is not Hammunition's to replace, or None when it is free or ours.

    Read-only and creating nothing: the plan calls it for every exposed name
    before any step runs, so a conflict is a refusal by name and not a failure
    in the middle of a transaction. A name that would leave *bin_dir* is a
    conflict too (:func:`wrapper_name_problem`).
    """
    misplaced = wrapper_name_problem(path, bin_dir)
    if misplaced is not None:
        return f"{unit} cannot put {path} on the PATH: {misplaced}"
    fd = _open_bin_dir(path.parent, create=False)
    if fd is None:
        return None
    try:
        state, why = _classify(fd, path.name, unit, ownership)
    finally:
        os.close(fd)
    return _refusal(path, unit, why) if state == "foreign" else None


def write_wrapper(path: Path, target: Path, unit: str, bin_dir: Path | None = None) -> str:
    """A two-line exec wrapper onto the operator's PATH -- only ever our own.

    The mechanics live in :func:`publish_wrapper`, shared with the node backend
    (#406); this supplies the venv wrapper's bytes and ownership rule.
    """
    publish_wrapper(path, wrapper_text(unit, target), unit, bin_dir)
    return f"wrote {path} -> {target}"


def publish_wrapper(
    path: Path,
    text: str,
    unit: str,
    bin_dir: Path | None = None,
    ownership: Ownership | None = None,
) -> None:
    """Put *text* at *path* in the operator's ``bin`` directory -- only ever over our own.

    Used by every backend that writes an executable wrapper there (venv, node);
    *ownership* says which existing bytes are ours to replace.

    The ownership rule (#288, D-022) and what stands behind it:

    - An entry already at *path* is replaced only if it is exactly a wrapper
      this backend wrote (:func:`_classify`). A symlink (a pipx install
      leaves them), a pip script, a directory, a FIFO, anything unreadable or
      oversized is refused by name and left alone. The plan has already
      refused the same cases (:func:`hammunition.plan.venv_wrapper_blockers`);
      this is the second look, because minutes of downloads separate the two.
    - The entry is reached through a descriptor on its directory, the new
      content is written to a temporary created ``O_CREAT|O_EXCL|O_NOFOLLOW``
      beside it, and published atomically: ``link()`` for a new name (it fails
      on an existing name, whatever that is, rather than replacing or following
      it) and ``rename()`` over our own previous wrapper (it replaces the
      directory entry, never the file a link points at).

    **Residual race, stated:** between the last ownership check and the
    ``rename()`` over an existing name, a process running as the same operator
    could replace that name with a file of its own and have it overwritten. It
    cannot redirect a write (nothing is written by path) and a process with
    the operator's uid could edit the file in place anyway, so no privilege is
    gained; the same shape, and the same stance, as ``prepare_tree`` in
    :mod:`hammunition.backends.source`, which also leaves root building by path
    inside an operator-owned directory open to an operator-uid race. A new
    name has no such window. The directory descriptor is not re-proven after
    the plan; a ``~/.local/bin`` swapped for a link between plan and write is
    followed as the operator's own (see :func:`_open_bin_dir`).
    """
    misplaced = wrapper_name_problem(path, bin_dir)
    if misplaced is not None:
        raise WrapperRefused(f"{unit} cannot put {path} on the PATH: {misplaced}")
    fd = _open_bin_dir(path.parent, create=True)
    assert fd is not None
    temporary = f".{path.name}.hammunition-{os.getpid()}-{secrets.token_hex(4)}"
    made = False
    try:
        state, why = _classify(fd, path.name, unit, ownership)
        if state == "foreign":
            raise WrapperRefused(_refusal(path, unit, why))
        # os.open's mode is filtered by the umask (077 -> 0700, 111 -> 0644,
        # 777 -> 0000), so the mode is set on the descriptor before the name is
        # published: a wrapper that is not executable is a success that did
        # nothing. fchmod on our own fresh descriptor cannot be redirected.
        tfd = os.open(
            temporary,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
            _WRAPPER_MODE,
            dir_fd=fd,
        )
        made = True
        os.fchmod(tfd, _WRAPPER_MODE)
        with os.fdopen(tfd, "wb") as handle:
            handle.write(text.encode(_TEXT_ENCODING))
        # The look that matters: after the temporary exists, immediately
        # before the entry changes.
        state, why = _classify(fd, path.name, unit, ownership)
        if state == "foreign":
            raise WrapperRefused(_refusal(path, unit, why))
        if state == "ours":
            os.rename(temporary, path.name, src_dir_fd=fd, dst_dir_fd=fd)
            made = False
        else:
            _publish_new(fd, temporary, path)
    finally:
        if made:
            with contextlib.suppress(OSError):
                os.unlink(temporary, dir_fd=fd)
        os.close(fd)


def _publish_new(fd: int, temporary: str, path: Path) -> None:
    """Give a name that did not exist its content, failing if it now does."""
    try:
        os.link(temporary, path.name, src_dir_fd=fd, dst_dir_fd=fd, follow_symlinks=False)
        return
    except FileExistsError as exc:
        raise WrapperRefused(
            f"{path} appeared while the wrapper was being written, and Hammunition did "
            f"not write it. It is left alone."
        ) from exc
    except OSError as exc:
        if exc.errno not in _NO_HARD_LINKS:
            raise
    # A filesystem without hard links: create the name exclusively instead.
    # Not atomic in content, but exclusive in name and never through a link.
    try:
        nfd = os.open(
            path.name,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
            _WRAPPER_MODE,
            dir_fd=fd,
        )
    except FileExistsError as exc:
        raise WrapperRefused(
            f"{path} appeared while the wrapper was being written, and Hammunition did "
            f"not write it. It is left alone."
        ) from exc
    try:
        os.fchmod(nfd, _WRAPPER_MODE)
        with (
            os.fdopen(nfd, "wb") as handle,
            os.fdopen(
                os.open(temporary, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd), "rb"
            ) as source,
        ):
            handle.write(source.read())
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(path.name, dir_fd=fd)
        raise


#: What a wrapper is published as, whatever the umask: owner-writable, executable by all.
_WRAPPER_MODE = 0o755

#: errnos that mean "this filesystem has no hard links", as opposed to a real failure.
_NO_HARD_LINKS = (errno.EPERM, errno.ENOTSUP, errno.EOPNOTSUPP, errno.EMLINK, errno.EXDEV)


def _licence_clause(block: VenvInstall) -> str:
    """The licence, stated on the plan line that installs the venv (D-033), or
    nothing for a block that declares none."""
    if block.licence is None:
        return ""
    return f"; licence: {block.licence} ({block.licence_url})"


class VenvBackend:
    """Plans venv installs. Steps only — the runner executes them.

    ``fetcher``/``build_root``/``prefix`` exist for the payload half of the
    hybrid (source-build-gaps #9): a verified archive extracted and
    tree-installed beside the venv that runs it. A backend built without
    them refuses a payload manifest by name rather than planning half an
    install.
    """

    def __init__(
        self,
        *,
        venv_root: Path,
        bin_dir: Path,
        fetcher: Fetcher | None = None,
        build_root: Path | None = None,
        prefix: Path = Path("/usr/local"),
        owner: str | None = None,
        context: ResolutionContext | None = None,
    ) -> None:
        self.context = context
        self.venv_root = venv_root
        self.bin_dir = bin_dir
        self.fetcher = fetcher
        #: The operator a payload tree is handed to (D-043); None keeps it root's.
        self.owner = owner
        self.build_root = build_root
        self.prefix = prefix

    def steps(self, manifest: PackageManifest, block: VenvInstall) -> list[Action | Command]:
        if block.payload is not None:
            # Before the venv, build and pip steps exist: pip's own dependencies
            # are not mirrored here, only the payload tree this block pins.
            self._preflight_payload(manifest, block.payload)
        venv = self.venv_root / manifest.name
        requirements = self.venv_root / f"{manifest.name}.requirements.txt"
        pip = venv / "bin" / "pip"

        steps: list[Action | Command] = [
            Action(
                kind="requirements",
                description=f"Stage {manifest.name}'s pinned requirements",
                detail=f"{len(block.requirements)} hash-pinned line(s) -> {requirements}",
                perform=partial(write_requirements, requirements, list(block.requirements)),
            ),
            Command(
                # The engine's own interpreter, never bare `python3`. The
                # engine requires Python >= 3.11, so sys.executable is
                # guaranteed to clear that bar; bare `python3` is the system
                # one, which on Ubuntu/Pop 22.04 is 3.10 — and a unit venv
                # built on 3.10 cannot install a modern hash-pinned tree
                # (numpy 2.5 dropped 3.10). Found deploying to a Pop 22.04
                # laptop, where nanovna-saver's numpy pin had no 3.10 wheel.
                # Resolved, not the engine venv's own symlink: on the field
                # laptop (2026-09-12) the engine ran from a worktree's .venv
                # that was removed mid-transaction, and 118 steps later this
                # spawned `<gone>/.venv/bin/python3 -m venv` and the run died.
                # The symlink pointed at /usr/bin/python3.13 the whole time.
                argv=(str(Path(sys.executable).resolve()), "-m", "venv", str(venv)),
                description=f"Create (or reuse) {manifest.name}'s virtualenv",
                requires_root=False,
            ),
            Command(
                argv=(
                    str(pip),
                    "install",
                    "--require-hashes",
                    "--no-input",
                    "--quiet",
                    "-r",
                    str(requirements),
                ),
                description=(
                    f"Install {manifest.name} into its venv — every wheel verified "
                    f"against the manifest's sha256 pins{_licence_clause(block)}"
                ),
                requires_root=False,
                env=dict(block.env),
                long_running=True,
            ),
        ]
        if block.payload is not None:
            steps.extend(self._payload_steps(manifest, block))
        for script in block.expose:
            wrapper = self.bin_dir / script
            target = venv / "bin" / script
            steps.append(
                Action(
                    kind="wrapper",
                    description=f"Put {script} on the operator's PATH",
                    detail=f"{wrapper} execs {target}",
                    perform=partial(write_wrapper, wrapper, target, manifest.name, self.bin_dir),
                )
            )
        return steps

    def _preflight_payload(self, manifest: PackageManifest, payload: RemoteArtifact) -> None:
        """The existing payload presence check, then the Bunker's answer for it."""
        from hammunition.backends.base import BackendError

        if self.fetcher is None or self.build_root is None:
            raise BackendError(
                f"{manifest.name} declares a venv payload and this backend was "
                f"built without a fetcher/build root. Skipping it would install "
                f"a venv that runs nothing."
            )
        preflight_payloads(
            manifest.name,
            ((payload, None),),
            context=self.context,
            cached=payload_cached(self.fetcher),
        )

    def _payload_steps(
        self, manifest: PackageManifest, block: VenvInstall
    ) -> list[Action | Command]:
        payload = block.payload
        assert payload is not None
        if self.fetcher is None or self.build_root is None:
            raise BackendError(
                f"{manifest.name} declares a venv payload and this backend was "
                f"built without a fetcher/build root. Skipping it would install "
                f"a venv that runs nothing."
            )
        layout = SourceLayout(root=self.build_root / f"{manifest.name}-{payload.sha256[:8]}")
        fetcher = self.fetcher
        steps: list[Action | Command] = [
            payload_action(manifest.name, payload, fetcher, label="payload tree"),
            Action(
                kind="extract",
                description=f"Unpack the {manifest.name} payload",
                detail=f"{fetcher.path_for(payload)} -> {layout.src}",
                perform=partial(_extract_payload, fetcher, payload, layout.src),
            ),
        ]
        if block.payload_build_script:
            # Run from the script's own directory: upstream build scripts
            # address their tree relative to themselves (auto_rx/build.sh
            # invokes `python3 -m autorx.version`, which only resolves from
            # auto_rx/ — measured on the first Debian run, 2026-08-30).
            script = Path(block.payload_build_script)
            steps.append(
                Command(
                    argv=("sh", script.name),
                    description=f"Run {manifest.name}'s payload build ({block.payload_build_script})",
                    cwd=layout.src / script.parent,
                )
            )
        steps.extend(
            tree_install_commands(
                name=manifest.name,
                source_tree=layout.src,
                prefix=self.prefix,
                owner=self.owner,
            )
        )
        return steps


def _extract_payload(fetcher: Fetcher, payload: RemoteArtifact, dest: Path) -> str:
    return extract(fetcher.path_for(payload), dest)
