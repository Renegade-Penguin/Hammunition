"""USGS US Topo 7.5-minute quads: which a region needs, and how each is
verified.  D-068.

A quad is one 7.5 x 7.5 minute map sheet, published by USGS (public domain)
as a GeoTIFF of the whole page, collar included, at
``<bucket>/StagedProducts/Maps/USTopo/GeoTIFF/<ST>/<stem>_<date>_TM_geo.tif``.
Which quads exist, their bounding boxes, sizes and S3 ETags are carried in
the catalog as ``catalog/data/ustopo-quads.txt``, generated by
``scripts/gen_ustopo_index.py`` from USGS's ``ustopo_current.csv`` and a
listing of the bucket, so the plan needs no network to know which quads a
region needs.

A region's quads are those whose bounding box overlaps a 1/8-degree cell
its Geofabrik outline touches (:func:`hammunition.copernicus.squares_touching`
at ``per_degree=8``). Most quads sit exactly on that grid; 6,638 of the
65,240 (Alaska, oversized and off-grid sheets, measured 2026-09-29) do not,
which is why the index carries each box as decimals.

Each quad is verified against the ETag the index carries, re-asked with a
``HEAD`` at plan time. A single-part upload's ETag is its MD5; a multipart
one, ``<hex>-<parts>``, is the MD5 of its parts' MD5s, reproduced by trying
each whole-MiB part size that splits the object into that many parts
(:func:`etag_matches`). Neither is a sha256 Hammunition measured, and the
plan says so quad by quad, in the Copernicus wording (:data:`UNPINNED`).

Pure apart from the injected probe.
"""

