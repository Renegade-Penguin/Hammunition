class RemovalError(Exception):
    """The removal could not be planned. The message carries every blocker."""


def installed_by_hammunition(log: TransactionLog) -> frozenset[str]:
    """Every apt package the log shows this engine installed and not removed.

    Replayed chronologically from ``command_end`` events with returncode 0.
    Unknown events are ignored, per the log's own reader contract.
    """
    attributed: set[str] = set()
    for entry in log.read():
        if entry.get("event") != "command_end" or entry.get("returncode") != 0:
            continue
        packages = _packages_after_dashes(entry.get("argv"))
        if packages is None:
            continue
        verb = _apt_verb(entry["argv"])
        if verb == "install":
            attributed.update(packages)
        elif verb == "remove":
            attributed.difference_update(packages)
    return frozenset(attributed)


def launcher_files_recorded(log: TransactionLog) -> frozenset[Path]:
    """Every wrapper and desktop entry the log shows an install wrote (#336).

    ``action_end`` entries of kind ``wrapper`` and ``desktop-entry`` carry the
    path they wrote as the first comma-separated part of ``detail``. The log
    names no unit on them, so :func:`plan_removal` asks each file whose it is
    by reading its own marker back; this only says which files to look at, so
    a manifest that has since lost its ``launchers`` block cannot hide them.
    """
    found: set[Path] = set()
    for entry in log.read():
        if entry.get("event") != "action_end":
            continue
        if entry.get("kind") not in ("wrapper", "desktop-entry"):
            continue
        detail = str(entry.get("detail", "")).split(", ", 1)[0]
        if detail.startswith("/"):
            found.add(Path(detail))
    return frozenset(found)


def _launcher_owner(path: Path) -> str | None:
    """The unit a generated wrapper or desktop entry says it belongs to."""
    try:
        text = path.read_text(errors="replace")
    except OSError:
        return None
    for line in text.splitlines()[:40]:
        for prefix in ("# generated by hammunition for ", "X-Hammunition-Package="):
            if line.startswith(prefix):
                return line[len(prefix) :].strip()
    return None


def _apt_verb(argv: Any) -> str | None:
    """``install`` or ``remove`` for an ``apt-get`` argv, else None.

    The verb is the first argument that is neither an option nor an option's
    value. Reading ``argv[1]`` was right until the engine began to write
    ``apt-get -o Acquire::Retries=3 install ...`` (#236), after which every
    apt install was invisible here: ``uninstall`` reported the package as "not
    installed by Hammunition" and left it. Only ``-o`` takes a separate value
    in the commands this engine writes; any other ``-x`` stands alone.
    """
    if not isinstance(argv, list) or len(argv) < 2 or argv[0] != "apt-get":
        return None
    if "--simulate" in argv:
        # The engine's own pre-flight (`install --simulate`, D-040 rule 6)
        # exits 0 and changes nothing: it must never attribute a package.
        return None
    index = 1
    while index < len(argv):
        arg = str(argv[index])
        if arg == "--":
            return None
        if arg == "-o":
            index += 2
            continue
        if arg.startswith("-"):
            index += 1
            continue
        return arg if arg in ("install", "remove") else None
    return None


def _packages_after_dashes(argv: Any) -> list[str] | None:
    """The package arguments of an ``apt-get install``/``remove`` argv, else None."""
    if _apt_verb(argv) is None or "--" not in argv:
        return None
    return [str(p) for p in argv[argv.index("--") + 1 :]]


def files_installed_by_hammunition(log: TransactionLog) -> frozenset[str]:
    """Every prefix file the log shows this engine installed and not removed.

    The engine's own file-install command is ``install -D -m <mode> <src>
    <dest>`` — ``0755`` for a prefix binary
    (:func:`~hammunition.backends.source.install_binary_commands`), ``0644``
    for an apt repository's source file and keyring
    (:class:`~hammunition.backends.apt_repo.AptRepoBackend`); a successful
    one attributes *dest*. Its own removal command is ``rm -f -- <dest>``; a
    successful one un-attributes it. Everything else — including the
    operator's own ``install`` runs, which are not in this log — is invisible
    here, which is the point.
    """
    attributed: set[str] = set()
    for entry in log.read():
        event = entry.get("event")
        if event == "action_end" and entry.get("kind") in ("install-binary", "install-data"):
            # The executable format installs in-process; its action_end
            # carries the destination as its detail (older logs carry no
            # detail field, and those installs stay unattributed — reported
            # and left in place rather than guessed at).
            # A data unit's install-data action (D-049) carries its destination
            # the same way: a file, or the unit's data directory for an archive.
            detail = entry.get("detail")
            if isinstance(detail, str) and detail.startswith("/"):
                attributed.add(detail)
            continue
        if event == "action_end" and entry.get("kind") == "remove-data":
            # A map region dropped from station config (D-057): the engine
            # removed the file it installed, so it is no longer ours.
            detail = entry.get("detail")
            if isinstance(detail, str):
                attributed.discard(detail)
            continue
        if event != "command_end" or entry.get("returncode") != 0:
            continue
        argv = entry.get("argv")
        if not isinstance(argv, list) or not argv:
            continue
        if argv[:3] == ["install", "-D", "-m"] and len(argv) == 6:
            attributed.add(str(argv[5]))
        elif argv[:2] == ["rm", "-f"] and "--" in argv:
            attributed.difference_update(str(p) for p in argv[argv.index("--") + 1 :])
    return frozenset(attributed)


def file_capabilities_installed_by_hammunition(log: TransactionLog) -> frozenset[str]:
    """Paths whose file capabilities this engine set and has not cleared."""
    attributed: set[str] = set()
    for entry in log.read():
        if entry.get("event") != "command_end" or entry.get("returncode") != 0:
            continue
        argv = entry.get("argv")
        if not isinstance(argv, list) or len(argv) != 3 or argv[0] != "setcap":
            continue
        path = str(argv[2])
        if argv[1] == "-r":
            attributed.discard(path)
        elif str(argv[1]).startswith("CAP_"):
            attributed.add(path)
    return frozenset(attributed)


def deb_attributed(log: TransactionLog, *, sha256: str, deb_package: str) -> bool:
    """Whether a vendor .deb with this digest is currently ours to remove.

    The fetch cache names artifacts ``<sha256>-<filename>``, so the record of
    the install carries the manifest's digest. The install itself runs inside
    the backend's ``install-deb`` Action — its apt-get never appears as a
    ``command_end`` of its own — so the digest is read from that action's
    recorded outcome (``installed <sha256>-<file> through apt``, the
    backend's own single-writer string). Replayed in order: the digest's
    install attributes it, a later successful ``apt-get remove`` naming
    *deb_package* un-attributes it. An operator's own reinstall of the
    distribution package is invisible to this log and changes nothing here —
    ``plan_removal`` still checks what is installed *now* before acting.
    """
    attributed = False
    for entry in log.read():
        event = entry.get("event")
        if event == "action_end" and entry.get("kind") == "install-deb":
            outcome = entry.get("outcome")
            if isinstance(outcome, str) and f"installed {sha256}-" in outcome:
                attributed = True
            continue
        if event != "command_end" or entry.get("returncode") != 0:
            continue
        packages = _packages_after_dashes(entry.get("argv"))
        if packages is None:
            continue
        verb = _apt_verb(entry["argv"])
        if verb == "install" and any(Path(str(p)).name.startswith(f"{sha256}-") for p in packages):
            attributed = True
        elif verb == "remove" and deb_package in packages:
            attributed = False
    return attributed


@dataclass(frozen=True)
class ArtifactRemoval:
    """One non-apt artifact an uninstall will remove, and on what authority.

    ``basis`` is printed beside the path so the operator sees *why* the
    engine believes this is its own work: ``namespaced`` (the path lives
    under a hammunition-owned directory), ``log`` (the transaction log
    attributes its installation), or ``marker`` (the file will be read back
    and removed only if it carries the engine's generated marker).
    """

    kind: Literal["venv", "tree", "binary", "capability", "wrapper", "desktop-entry", "apt-repo"]
    path: Path
    basis: Literal["namespaced", "log", "marker"]
    requires_root: bool = False


@dataclass(frozen=True)
class RemovalPaths:
    """Where this machine's non-apt artifacts live, from :mod:`~hammunition.paths`."""

    prefix: Path
    venv_root: Path
    bin_dir: Path
    applications_dir: Path
    node_root: Path | None = None
    """Where node trees live. Optional so older callers plan as before; a
    node unit's removal refuses by name without it rather than guessing."""


@dataclass(frozen=True)
class RemovalPlan:
    """What an uninstall will do, and everything it deliberately will not."""

    to_remove: dict[str, list[str]]
    """Unit name -> the apt packages that will be removed for it."""

    left_foreign: dict[str, list[str]]
    """Unit name -> installed packages left in place: not installed by us."""

    already_absent: dict[str, list[str]]
    """Unit name -> attributed packages that are already not installed."""

    artifacts: dict[str, list[ArtifactRemoval]] = field(default_factory=dict)
    """Unit name -> non-apt artifacts (venvs, trees, binaries, launchers)."""

    left_unattributed: dict[str, list[str]] = field(default_factory=dict)
    """Unit name -> present prefix files left in place: the log does not
    attribute them, so they predate us or arrived by another road."""

    kept_shared: dict[str, list[str]] = field(default_factory=dict)
    """Unit name -> files this engine installed and left, because another
    installed unit still needs them: the tray's device helper, which both tray
    units install."""

    left_in_place: dict[str, list[str]] = field(default_factory=dict)
    """Unit name -> the home paths its manifest says uninstall leaves (#289).
    Disclosure only, copied from the manifest for a unit this removal actually
    removes something of; nothing reads these to delete."""

    apt_packages: tuple[str, ...] = field(init=False)
    """The flat, sorted set the single ``apt-get remove`` will name."""

    def __post_init__(self) -> None:
        flat = sorted({p for packages in self.to_remove.values() for p in packages})
        object.__setattr__(self, "apt_packages", tuple(flat))


def plan_removal(
    names: list[str],
    *,
    catalog: dict[str, PackageManifest],
    profiles: dict[str, ProfileManifest],
    target: Target,
    attributed: frozenset[str],
    states: dict[str, AptPackageState],
    paths: RemovalPaths,
    attributed_files: frozenset[str] = frozenset(),
    attributed_capabilities: frozenset[str] = frozenset(),
    log: TransactionLog | None = None,
    owners: Callable[[Collection[str]], Mapping[str, str]] | None = None,
) -> RemovalPlan:
    """Resolve names to a removal plan, or raise with every blocker at once.

    ``states`` is the current apt view of every package the plan touches
    (from ``AptBackend.probe``) — what is installed *now*, not what the log
    said at install time. ``attributed_files`` is
    :func:`files_installed_by_hammunition` over the same log; ``log`` itself
    is only consulted for vendor-.deb digest attribution. ``owners`` answers
    which package owns a path (``dpkg-query -S`` by default): the log says what
    this engine once installed, and a file a package has since taken over is the
    package's to remove, so it is asked again here and the file is left.
    """
    blockers: list[str] = []
    units: list[str] = []
    for name in names:
        if name in profiles:
            units.extend(profiles[name].packages)
        elif name in catalog:
            units.append(name)
        else:
            blockers.append(f"{name}: not a package or profile in this catalog")

    to_remove: dict[str, list[str]] = {}
    left_foreign: dict[str, list[str]] = {}
    already_absent: dict[str, list[str]] = {}
    artifacts: dict[str, list[ArtifactRemoval]] = {}
    left_unattributed: dict[str, list[str]] = {}
    kept_shared: dict[str, list[str]] = {}
    recorded_launchers = launcher_files_recorded(log) if log is not None else frozenset()

    def add(unit: str, removal: ArtifactRemoval) -> None:
        if removal.path.exists() or removal.path.is_symlink():
            held = artifacts.setdefault(unit, [])
            if not any(r.path == removal.path and r.kind == removal.kind for r in held):
                held.append(removal)

    def plan_recorded_launchers(unit: str) -> None:
        """Launcher files the log says an install wrote for *unit* (#336).

        The manifest's own ``launchers`` are planned separately and stay a
        second source; this one survives a manifest that dropped the block or
        a unit since retired. A file whose marker names another unit is that
        unit's. A file with no marker is the operator's replacement: left, and
        reported when its name is this unit's.
        """
        for recorded in sorted(recorded_launchers):
            if not (recorded.exists() or recorded.is_symlink()):
                continue
            owner = _launcher_owner(recorded)
            if owner == unit:
                if recorded.suffix == ".desktop":
                    add(unit, ArtifactRemoval("desktop-entry", recorded, "marker"))
                else:
                    add(unit, ArtifactRemoval("wrapper", recorded, "marker"))
            elif owner is None and recorded.name in (unit, f"hammunition-{unit}.desktop"):
                left_unattributed.setdefault(unit, []).append(str(recorded))

    def plan_repos(unit: str, manifest: PackageManifest) -> None:
        """The repository files the install wrote — on log evidence only (D-040).

        The log recorded each ``install -D -m 0644`` destination exactly, so
        the match is on the recorded path, never on a directory listing: a
        ``code.sources`` the operator wrote by hand is not in this log and is
        not touched.
        """
        for repo in manifest.apt_repos:
            names = {f"{repo.name}.sources", f"{repo.name}.gpg"}
            for path in sorted(attributed_files):
                if Path(path).name in names:
                    add(unit, ArtifactRemoval("apt-repo", Path(path), "log", requires_root=True))

    def plan_binaries(unit: str, manifest: PackageManifest, block: InstallBlock) -> None:
        """Prefix binaries the engine copied — removable only on log evidence.

        Read from the resolved block, because the block may name its own
        (issue #69): removing the manifest-level names on a machine that
        installed the block's would leave the installed files behind and
        report the removal done.
        """
        for binary in effective_binaries(manifest, block):
            dest = paths.prefix / "bin" / binary.install_as
            if str(dest) in attributed_files:
                if str(dest) in attributed_capabilities and any(
                    modification.kind == "file_capability"
                    and modification.binary == binary.install_as
                    for modification in manifest.system_modifications
                ):
                    add(unit, ArtifactRemoval("capability", dest, "log", requires_root=True))
                add(unit, ArtifactRemoval("binary", dest, "log", requires_root=True))
            elif dest.exists():
                left_unattributed.setdefault(unit, []).append(str(dest))

    def package_owned(candidates: Collection[Path]) -> Mapping[str, str]:
        found = (owners or devctl_helper.dpkg_owners)([str(c) for c in candidates])
        return {path: pkg for path, pkg in found.items()}

    def plan_placed(unit: str, install: BinaryInstall) -> None:
        """What a ``binary`` block spread over the filesystem, on log evidence.

        Files first, so each is un-attributed by its own ``rm -f``; then the
        directories that held only this unit's files, which go whole.
        """
        taken = package_owned([under_prefix(p.dest, paths.prefix) for p in install.placements])
        for placement in install.placements:
            dest = under_prefix(placement.dest, paths.prefix)
            if str(dest) in taken:
                left_unattributed.setdefault(unit, []).append(str(dest))
            elif str(dest) in attributed_files:
                add(unit, ArtifactRemoval("binary", dest, "log", requires_root=True))
            elif dest.exists():
                left_unattributed.setdefault(unit, []).append(str(dest))
        for directory in install.placement_dirs:
            inside = directory + "/"
            if any(
                str(under_prefix(p.dest, paths.prefix)) in attributed_files
                and str(under_prefix(p.dest, paths.prefix)) not in taken
                for p in install.placements
                if p.dest.startswith(inside)
            ):
                add(
                    unit,
                    ArtifactRemoval(
                        "tree", under_prefix(directory, paths.prefix), "log", requires_root=True
                    ),
                )
        if install.devctl_helper is not None:
            plan_helper_removal(unit)

    def helper_needed_elsewhere() -> bool:
        """Another unit, one this removal leaves, whose files are still on disk."""
        for other, other_manifest in catalog.items():
            if other in units:
                continue
            other_block = other_manifest.resolve(target.distro, target.version, target.arch)
            other_install = other_block.install if other_block is not None else None
            if (
                isinstance(other_install, BinaryInstall)
                and other_install.devctl_helper is not None
                and any(
                    under_prefix(p.dest, paths.prefix).is_file() for p in other_install.placements
                )
            ):
                return True
        return False

    def plan_helper_removal(unit: str) -> None:
        """The tray's device helper, removed only when this engine put it there
        and no other tray unit that is still installed calls it."""
        libdir = under_prefix(LIBDIR, paths.prefix)
        entry = libdir / ENTRY_NAME
        wrapper = under_prefix(HELPER_PATH, paths.prefix)
        policy = Path(POLICY_PATH)
        if str(entry) not in attributed_files or package_owned([policy]):
            # Another owner's (a .deb now owns the action, the tray's own
            # installer), or never ours.
            if wrapper.exists():
                left_unattributed.setdefault(unit, []).append(str(wrapper))
            return
        if helper_needed_elsewhere():
            held = [str(p) for p in (wrapper, policy, libdir) if p.exists()]
            if held:
                kept_shared.setdefault(unit, []).extend(held)
            return
        # Every file the log attributes goes by its own `rm -f --`, so the replay
        # un-attributes each; the directory then goes whole.
        inside = f"{libdir}/"
        files = [
            wrapper,
            policy,
            *(Path(f) for f in sorted(attributed_files) if f.startswith(inside)),
        ]
        for path in files:
            if str(path) in attributed_files:
                add(unit, ArtifactRemoval("binary", path, "log", requires_root=True))
        add(unit, ArtifactRemoval("tree", libdir, "log", requires_root=True))

    for unit in dict.fromkeys(units):  # preserve order, drop duplicates
        manifest = catalog[unit]
        block = manifest.resolve(target.distro, target.version, target.arch)
        if block is None:
            # Nothing installable here means nothing to remove here; if the
            # log attributed packages under another distro, that machine's
            # log is not this machine's.
            already_absent[unit] = []
            plan_recorded_launchers(unit)
            continue
        install = block.install

        if isinstance(install, AptInstall):
            for package in install.packages:
                state = states.get(package)
                currently = state is not None and state.is_installed
                if package in attributed and currently:
                    to_remove.setdefault(unit, []).append(package)
                elif currently:
                    left_foreign.setdefault(unit, []).append(package)
                else:
                    already_absent.setdefault(unit, []).append(package)
            plan_repos(unit, manifest)

        elif isinstance(install, VenvInstall):
            add(
                unit,
                ArtifactRemoval("venv", paths.venv_root / manifest.name, "namespaced"),
            )
            # The backend stages the hash-pinned requirements file beside the
            # venv; it is namespaced the same way and leaves with it.
            add(
                unit,
                ArtifactRemoval(
                    "venv",
                    paths.venv_root / f"{manifest.name}.requirements.txt",
                    "namespaced",
                ),
            )
            for script in install.expose:
                add(unit, ArtifactRemoval("wrapper", paths.bin_dir / script, "marker"))

        elif isinstance(install, NodeInstall):
            if paths.node_root is None:
                blockers.append(
                    f"{unit}: is a node build and this removal was planned without "
                    f"a node root — nothing knows where its tree is"
                )
                continue
            # Per-user and namespaced, like a venv; removed with a plain rm as
            # the operator, never root.
            add(
                unit,
                ArtifactRemoval("tree", paths.node_root / manifest.name, "namespaced"),
            )
            add(
                unit,
                ArtifactRemoval(
                    "wrapper", paths.bin_dir / (install.command or manifest.name), "marker"
                ),
            )

        elif isinstance(install, BinaryInstall):
            if install.format == "deb":
                deb_pkg = install.deb_package
                assert deb_pkg is not None  # schema validator guarantees it
                state = states.get(deb_pkg)
                currently = state is not None and state.is_installed
                ours = log is not None and deb_attributed(
                    log, sha256=install.artifact.sha256, deb_package=deb_pkg
                )
                if currently and ours:
                    to_remove.setdefault(unit, []).append(deb_pkg)
                elif currently:
                    left_foreign.setdefault(unit, []).append(deb_pkg)
                else:
                    already_absent.setdefault(unit, []).append(deb_pkg)
            else:
                plan_binaries(unit, manifest, block)
                if install.install_tree:
                    add(
                        unit,
                        ArtifactRemoval(
                            "tree",
                            paths.prefix / "share" / "hammunition" / manifest.name,
                            "namespaced",
                            requires_root=True,
                        ),
                    )
                plan_placed(unit, install)

        elif isinstance(
            install,
            DataInstall
            | RegionalDataInstall
            | DemTilesInstall
            | TopoQuadsInstall
            | RegisterInstall
            | DerivedDataInstall
            | KiwixBooksInstall
            | MwmRegionsInstall,
        ):
            # D-049: a data unit's files live only under its namespaced data
            # directory, which nothing but this engine writes; removed whole.
            # Map regions and their converted maps (D-057), and terrain tiles
            # with what is drawn from them (D-061), live the same way.
            add(
                unit,
                ArtifactRemoval(
                    "tree",
                    paths.prefix / "share" / "hammunition" / "data" / manifest.name,
                    "namespaced",
                    requires_root=True,
                ),
            )
            if isinstance(install, DerivedDataInstall) and install.tool is not None:
                # D-067: the converter's pinned program, kept in the unit's own
                # namespaced directory beside the data tree, never inside it.
                add(
                    unit,
                    ArtifactRemoval(
                        "tree",
                        paths.prefix / "share" / "hammunition" / manifest.name,
                        "namespaced",
                        requires_root=True,
                    ),
                )
        elif isinstance(install, SourceInstall | GitInstall):
            reversible = not install.provides_install_target or install.install_tree
            if not reversible:
                blockers.append(
                    f"{unit}: built from {install.method} with a real `make "
                    f"install` into {paths.prefix}, which leaves no file "
                    f"manifest to reverse — a staged, recorded install is the "
                    f"planned fix. What it wrote is in the transaction log"
                )
                continue
            if not install.provides_install_target:
                plan_binaries(unit, manifest, block)
            if install.install_tree:
                add(
                    unit,
                    ArtifactRemoval(
                        "tree",
                        paths.prefix / "share" / "hammunition" / manifest.name,
                        "namespaced",
                        requires_root=True,
                    ),
                )
        else:
            blockers.append(
                f"{unit}: installed via the {install.method} backend, and "
                f"uninstall for {install.method} is not implemented — what "
                f"it wrote is in the transaction log"
            )
            continue

        plan_recorded_launchers(unit)
        for launcher in manifest.launchers:
            add(unit, ArtifactRemoval("wrapper", paths.bin_dir / launcher.name, "marker"))
            add(
                unit,
                ArtifactRemoval(
                    "desktop-entry",
                    paths.applications_dir / f"hammunition-{launcher.name}.desktop",
                    "marker",
                ),
            )

    left_in_place: dict[str, list[str]] = {}
    for unit in dict.fromkeys(units):
        declared = catalog[unit].left_in_place
        if declared and (to_remove.get(unit) or artifacts.get(unit)):
            left_in_place[unit] = list(declared)

    if blockers:
        raise RemovalError("this removal cannot be planned:\n  " + "\n  ".join(sorted(blockers)))
    return RemovalPlan(
        to_remove=to_remove,
        left_foreign=left_foreign,
        already_absent=already_absent,
        artifacts=artifacts,
        left_unattributed=left_unattributed,
        kept_shared=kept_shared,
        left_in_place=left_in_place,
    )
