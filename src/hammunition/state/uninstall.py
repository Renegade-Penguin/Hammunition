"""Removal of what Hammunition itself installed.

D-004 and DESIGN.md §7 fix the promise: no rollback, a transaction log, and an
``uninstall`` that removes what Hammunition added and reports honestly on what
it cannot safely reverse.

## What "Hammunition installed it" means

Attribution replays the transaction log's events in order; the command's own
recorded outcome is the source of truth, not the surrounding transaction —
a run that died on command 3 of 5 still installed whatever command 2
installed, and reading only completed transactions would deny that. Four
attribution routes, each exact:

- **apt packages** — ``command_end`` for ``apt-get install``/``remove``
  exiting 0 attributes/un-attributes the packages after ``--``.
- **files under the prefix** — ``command_end`` for the engine's own
  ``install -D -m 0755 … <dest>`` attributes *dest*; a successful
  ``rm -f -- <dest>`` un-attributes it. Nothing else in ``/usr/local/bin``
  is ever touched: a same-named file the operator put there predates the
  log and stays.
- **vendor .debs** — the fetch cache names every artifact
  ``<sha256>-<filename>``, so the recorded install argv carries the
  manifest's own digest. A deb unit is attributed when its digest appears
  in a successful ``apt-get install`` and its declared ``deb_package`` has
  not been apt-removed since.
- **namespaced trees and venvs** — ``<prefix>/share/hammunition/<name>``
  and the per-user ``venvs/<name>`` can only be ours; existence is
  attribution.

Wrappers and desktop entries in the operator's home are removed only after
reading them back: the launcher wrapper's ``generated by hammunition`` line,
a venv wrapper's exec into our venv tree, a desktop entry's
``X-Hammunition-Package`` key. A same-named file without the marker is
reported and left.

## What is refused, by name

- A source or git unit whose build ran a real ``make install`` into the
  shared prefix: there is no file manifest to reverse, and pretending with
  a file sweep would be the shim CLAUDE.md forbids. The refusal names the
  unit and the gap (a staged, recorded install is the future fix).
- A package that is installed but was not installed by Hammunition: it was
  there before us (or arrived by another road), and removing it would exceed
  the promise. It is reported and left in place.

Shared dependencies that apt pulled in are left for ``apt autoremove``, and
the plan says so: removing them by name risks removing what another unit —
or the user's own work — still needs. File capabilities this engine applied
are cleared before their attributed binary is removed. Group memberships and
written config files are not yet reversed; the log records them, and the plan
says that too.
"""

